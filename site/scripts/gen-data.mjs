// Prepares everything the docs site shows, straight from the design-system build output:
// copies dist/*.css next to the app, splits the override CSS per component, resolves the tokens each section uses.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildChangelog } from './changelog.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const out = join(here, '..', 'src', 'generated');
mkdirSync(out, { recursive: true });

const tokensCss = readFileSync(join(root, 'dist', 'tokens.css'), 'utf8');
const overrideCss = readFileSync(join(root, 'dist', 'ng-zorro-override.css'), 'utf8');
copyFileSync(join(root, 'dist', 'tokens.css'), join(out, 'tokens.css'));
copyFileSync(join(root, 'dist', 'ng-zorro-override.css'), join(out, 'ng-zorro-override.css'));

// Section boundaries: the first line that starts each component's block in src/ng-zorro-override.css.
const starts = [
  ['input', /^\/\* Targets ng-zorro-antd/m],
  ['button', /^\/\* -{20,}\n\s+Button\./m],
  ['checkbox-radio', /^\/\* -{20,}\n\s+Checkbox/m],
  ['select', /^\/\* -{20,}\n\s+Select/m],
  ['switch', /^\/\* -{20,}\n\s+Switch/m],
  ['tag', /^\/\* Tag \/ status badge/m],
  ['chip-filter', /^\/\* Chip \/ filter/m],
  ['badge', /^\/\* Badge\./m],
  ['pagination', /^\/\* Pagination\./m],
  ['tab', /^\/\* Tab\./m],
  ['tooltip', /^\/\* Tooltip\./m],
  ['breadcrumb', /^\/\* Breadcrumb\./m],
  ['divider', /^\/\* Divider\./m],
  ['alert', /^\/\* Alert\./m],
  ['message', /^\/\* Message \/ Snackbar\./m],
  ['modal', /^\/\* Modal \/ dialog\./m],
  ['empty', /^\/\* Empty\. Source/m],
];
const idx = starts.map(([id, re]) => {
  const m = re.exec(overrideCss);
  if (!m) throw new Error(`gen-data: section marker for "${id}" not found in ng-zorro-override.css`);
  return [id, m.index];
});
if (idx.some((v, i) => i && v[1] <= idx[i - 1][1])) throw new Error('gen-data: section markers are out of order');
const sections = {};
idx.forEach(([id, from], i) => {
  sections[id] = { css: overrideCss.slice(from, i + 1 < idx.length ? idx[i + 1][1] : undefined).trim() + '\n' };
});

// Token table: name -> {value, description}, in file order.
const tokens = [];
const byName = new Map();
for (const m of tokensCss.matchAll(/^\s*(--aibox-[\w-]+):\s*([^;]+);(?:\s*\/\*\*\s*(.*?)\s*\*\/)?/gm)) {
  const t = { name: m[1], value: m[2].trim(), description: m[3] ?? '' };
  tokens.push(t);
  byName.set(t.name, t);
}
const deps = (name, seen) => {
  if (seen.has(name)) return;
  const t = byName.get(name);
  if (!t) return;
  seen.add(name);
  for (const d of t.value.matchAll(/var\((--aibox-[\w-]+)\)/g)) deps(d[1], seen);
};
// Sections that build on another section's rules (chip/filter reuses the tag base) ship that section's CSS first.
const requires = { 'chip-filter': ['tag'], pagination: ['select'], message: ['alert'], modal: ['button'] };
for (const [id, deps_] of Object.entries(requires)) {
  sections[id].requires = deps_;
  sections[id].css = deps_.map((d) => sections[d].css).join('\n') + '\n' + sections[id].css;
}
for (const s of Object.values(sections)) {
  const used = new Set();
  for (const m of s.css.matchAll(/var\((--aibox-[\w-]+)/g)) deps(m[1], used);
  s.tokenNames = tokens.filter((t) => used.has(t.name)).map((t) => t.name);
  s.tokensCss = ':root {\n' + tokens.filter((t) => used.has(t.name)).map((t) => `  ${t.name}: ${t.value};`).join('\n') + '\n}\n';
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const nz = JSON.parse(readFileSync(join(here, '..', 'node_modules', 'ng-zorro-antd', 'package.json'), 'utf8'));
const ng = JSON.parse(readFileSync(join(here, '..', 'node_modules', '@angular', 'core', 'package.json'), 'utf8'));
const meta = { dsVersion: pkg.version, nzVersion: nz.version, angularVersion: ng.version, overrideBytes: Buffer.byteLength(overrideCss) };

writeFileSync(join(out, 'meta.ts'), `// Generated by scripts/gen-data.mjs - do not edit.\nexport const META = ${JSON.stringify(meta, null, 2)};\n`);
writeFileSync(
  join(out, 'data.ts'),
  `// Generated by scripts/gen-data.mjs - do not edit.\n` +
    `export const CSS_SECTIONS: Record<string, { css: string; tokensCss: string; tokenNames: string[]; requires?: string[] }> = ${JSON.stringify(sections, null, 2)};\n` +
    `export const TOKENS: { name: string; value: string; description: string }[] = ${JSON.stringify(tokens)};\n`,
);
const releases = buildChangelog(root);
writeFileSync(
  join(out, 'changelog.ts'),
  `// Generated by scripts/gen-data.mjs from release-notes/*.md - do not edit.\n` +
    `export interface ChangelogSection { title: string; kind: 'new' | 'fix' | 'upgrade' | 'gap' | 'other'; html: string }\n` +
    `export interface ChangelogRelease { version: string; title: string; date: string; intro: string; sections: ChangelogSection[] }\n` +
    `export const RELEASES: ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};\n`,
);
console.log(`gen-data: ${Object.keys(sections).join(', ')}; ${releases.length} releases; ${tokens.length} tokens; ng-zorro-antd ${nz.version}, Angular ${ng.version}, design system ${pkg.version}`);
